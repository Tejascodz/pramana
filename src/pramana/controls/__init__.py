"""Control library: framework catalogues, the check crosswalk and the regulatory calendar."""

from __future__ import annotations

from dataclasses import dataclass, field
from functools import lru_cache
from importlib import resources
from typing import Any

import yaml

FRAMEWORK_FILES = (
    "nist_ai_rmf.yaml",
    "nist_genai_profile.yaml",
    "iso_42001.yaml",
    "eu_ai_act.yaml",
    "india_aigg.yaml",
    "owasp_llm.yaml",
)


@dataclass(frozen=True)
class Control:
    framework: str
    id: str
    group: str
    title: str
    evidence: str
    applies_to: tuple[str, ...] = ("all",)

    @property
    def ref(self) -> str:
        return f"{self.framework}:{self.id}"


@dataclass
class Framework:
    id: str
    name: str
    version: str
    source: str
    group_label: str
    controls: list[Control] = field(default_factory=list)


@dataclass
class ControlLibrary:
    frameworks: dict[str, Framework]
    crosswalk: dict[str, dict[str, Any]]
    calendar: dict[str, Any]

    def control(self, ref: str) -> Control:
        framework_id, control_id = ref.split(":", 1)
        for control in self.frameworks[framework_id].controls:
            if control.id == control_id:
                return control
        raise KeyError(ref)

    def all_controls(self) -> list[Control]:
        return [c for fw in self.frameworks.values() for c in fw.controls]

    def controls_for_check(self, check_id: str) -> list[str]:
        return list(self.crosswalk.get(check_id, {}).get("controls", []))

    def checks_for_control(self, ref: str) -> list[str]:
        return [cid for cid, entry in self.crosswalk.items() if ref in entry.get("controls", [])]

    def validate(self) -> list[str]:
        """Return a list of crosswalk references that do not exist in any framework."""
        known = {c.ref for c in self.all_controls()}
        problems = []
        for check_id, entry in self.crosswalk.items():
            for ref in entry.get("controls", []):
                if ref not in known:
                    problems.append(f"{check_id} -> {ref}")
        return problems


def _read_yaml(name: str) -> dict[str, Any]:
    text = resources.files("pramana.controls").joinpath("data", name).read_text(encoding="utf-8")
    return yaml.safe_load(text)


@lru_cache(maxsize=1)
def load_library() -> ControlLibrary:
    frameworks: dict[str, Framework] = {}
    for filename in FRAMEWORK_FILES:
        raw = _read_yaml(filename)
        meta = raw["framework"]
        fw = Framework(
            id=meta["id"],
            name=meta["name"],
            version=str(meta["version"]),
            source=meta["source"],
            group_label=meta.get("group_label", "Group"),
        )
        for item in raw["controls"]:
            fw.controls.append(
                Control(
                    framework=fw.id,
                    id=str(item["id"]),
                    group=str(item["group"]),
                    title=item["title"],
                    evidence=item.get("evidence", "both"),
                    applies_to=tuple(item.get("applies_to", ["all"])),
                )
            )
        frameworks[fw.id] = fw
    crosswalk = _read_yaml("crosswalk.yaml")["checks"]
    calendar = _read_yaml("regulatory_calendar.yaml")
    return ControlLibrary(frameworks=frameworks, crosswalk=crosswalk, calendar=calendar)


def crosswalk_markdown(library: ControlLibrary | None = None) -> str:
    """Render the check-to-control crosswalk as a Markdown document."""
    lib = library or load_library()
    lines = [
        "# Control crosswalk",
        "",
        "Generated by `pramana controls --markdown`. Each Pramana check is listed with the",
        "failure mode it targets and the framework controls its evidence supports.",
        "",
    ]
    for check_id, entry in lib.crosswalk.items():
        lines.append(f"## `{check_id}`")
        lines.append("")
        lines.append(f"- **Failure mode:** {entry['failure_mode']}")
        lines.append(f"- **Effect if missed:** {entry['effect']}")
        lines.append("")
        lines.append("| Framework | Control | Title |")
        lines.append("|---|---|---|")
        for ref in entry["controls"]:
            control = lib.control(ref)
            lines.append(
                f"| {lib.frameworks[control.framework].name} | {control.id} | {control.title} |"
            )
        lines.append("")
    lines.append("## Framework catalogues")
    lines.append("")
    for fw in lib.frameworks.values():
        lines.append(
            f"- **{fw.name}** ({fw.version}): {len(fw.controls)} controls. Source: {fw.source}"
        )
    lines.append("")
    return "\n".join(lines)
